"""Read-only security checks against the DEPLOYED acxdmem stacks (design.md section 6).

Complements the synth-time assertions in tests/test_stacks.py with the live state:

    1. No Lambda Function URL on any acxdmem function
    2. Every Lambda resource-policy statement names apigateway.amazonaws.com (never "*") and
       carries a SourceArn on this API
    3. Every API method uses a CUSTOM (Lambda REQUEST) authorizer, one per route
    4. Stage throttling is on; data trace is off
    5. The API security policy refuses TLS 1.0/1.1 and the endpoint access mode is STRICT
    6. Unauthenticated calls are rejected (401 without the header, 403 with a wrong secret,
       403 with the OTHER route's secret)

Check 6 sends HTTPS requests to the API with synthetic bodies and wrong or missing secrets
only; it never reads a secret value except to prove the cross-route rejection, and never
prints one. The endpoint secrets are found through the ``<prefix>-api`` stack outputs
(their names are generated by CloudFormation).

Usage:
    python3 scripts/verify_live_security.py --api-id <rest api id> [--profile P] [--region R]
        [--prefix acxdmem]

``--region`` defaults to the profile's or environment's region; ``--prefix`` is the
``resourcePrefix`` context value (default ``acxdmem``).
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.error
import urllib.request

import boto3

DEFAULT_PREFIX = "acxdmem"
SYNTHETIC_PROFILE = "0" * 32
# Regional REST API policies that refuse TLS 1.0 and 1.1 (TLS_1_0, the default, accepts them).
TLS12_MIN_POLICIES = {
    "TLS_1_2",
    "SecurityPolicy_TLS13_1_3_2025_09",
    "SecurityPolicy_TLS13_1_3_FIPS_2025_09",
    "SecurityPolicy_TLS13_1_2_PFS_PQ_2025_09",
    "SecurityPolicy_TLS13_1_2_FIPS_PQ_2025_09",
    "SecurityPolicy_TLS13_1_2_FIPS_PFS_PQ_2025_09",
    "SecurityPolicy_TLS13_1_2_PQ_2025_09",
    "SecurityPolicy_TLS13_1_2_2021_06",
}


def _post(url: str, headers: dict[str, str], body: dict) -> int:
    if not url.startswith("https://"):
        raise ValueError(f"refusing non-HTTPS URL {url!r}")
    req = urllib.request.Request(url, data=json.dumps(body).encode(), method="POST",
                                 headers={"content-type": "application/json", **headers})
    try:
        # https only (checked above), so no file:// or custom scheme.
        with urllib.request.urlopen(req, timeout=10) as resp:  # nosec B310
            return resp.status
    except urllib.error.HTTPError as exc:
        return exc.code


def endpoint_secret_arns(cfn, stack_name: str) -> dict[str, str]:
    """``{"read": arn, "write": arn}`` from the API stack's outputs."""
    stack = cfn.describe_stacks(StackName=stack_name)["Stacks"][0]
    outputs = {o["OutputKey"]: o["OutputValue"] for o in stack.get("Outputs", [])}
    return {r: outputs[f"EndpointSecret{r.capitalize()}Arn"] for r in ("read", "write")}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--api-id", required=True)
    ap.add_argument("--stage", default="v1")
    ap.add_argument("--profile")
    ap.add_argument("--region", help="default: the profile's or environment's region")
    ap.add_argument("--prefix", default=DEFAULT_PREFIX, help="resourcePrefix (default acxdmem)")
    args = ap.parse_args()
    s = boto3.Session(profile_name=args.profile, region_name=args.region)
    region = s.region_name
    if not region:
        ap.error("no region: pass --region or configure one for the profile")
    prefix = args.prefix
    lam, apigw, sm = s.client("lambda"), s.client("apigateway"), s.client("secretsmanager")
    account = s.client("sts").get_caller_identity()["Account"]
    api_arn = f"arn:aws:execute-api:{region}:{account}:{args.api_id}/"
    failures: list[str] = []

    def check(ok: bool, label: str) -> None:
        print(f"[{'PASS' if ok else 'FAIL'}] {label}")
        if not ok:
            failures.append(label)

    names = [f["FunctionName"] for page in lam.get_paginator("list_functions").paginate()
             for f in page["Functions"] if f["FunctionName"].startswith(f"{prefix}-")]
    check(bool(names), f"found {len(names)} {prefix} functions")
    for name in sorted(names):
        urls = lam.list_function_url_configs(FunctionName=name)["FunctionUrlConfigs"]
        check(not urls, f"{name}: no Function URL")
        try:
            policy = json.loads(lam.get_policy(FunctionName=name)["Policy"])
        except lam.exceptions.ResourceNotFoundException:
            print(f"       {name}: no resource policy")
            continue
        for st in policy["Statement"]:
            principal = st.get("Principal")
            src = st.get("Condition", {}).get("ArnLike", {}).get("AWS:SourceArn", "")
            ok = principal == {"Service": "apigateway.amazonaws.com"} and src.startswith(api_arn)
            check(ok, f"{name}: statement {st.get('Sid')} principal {principal} SourceArn {src}")

    resources = apigw.get_resources(restApiId=args.api_id, limit=500)["items"]
    authorizers: dict[str, str] = {}
    for r in resources:
        for method in (r.get("resourceMethods") or {}):
            m = apigw.get_method(restApiId=args.api_id, resourceId=r["id"], httpMethod=method)
            ok = m.get("authorizationType") == "CUSTOM" and bool(m.get("authorizerId"))
            check(ok, f"{method} {r['path']}: authorization {m.get('authorizationType')} {m.get('authorizerId')}")
            authorizers[r["path"]] = m.get("authorizerId", "")
    check(len(set(authorizers.values())) == len(authorizers), "one authorizer per route")

    stage = apigw.get_stage(restApiId=args.api_id, stageName=args.stage)
    ms = stage.get("methodSettings", {}).get("*/*", {})
    check(ms.get("throttlingRateLimit", 0) > 0 and ms.get("throttlingBurstLimit", 0) > 0,
          f"stage throttling {ms.get('throttlingRateLimit')} rps / burst {ms.get('throttlingBurstLimit')}")
    check(ms.get("dataTraceEnabled") is False, "data trace off")

    api = apigw.get_rest_api(restApiId=args.api_id)
    policy_name = api.get("securityPolicy", "")
    check(policy_name in TLS12_MIN_POLICIES, f"security policy {policy_name} (TLS 1.2 minimum)")
    check(api.get("endpointAccessMode") == "STRICT",
          f"endpoint access mode {api.get('endpointAccessMode')} (want STRICT)")

    base = f"https://{args.api_id}.execute-api.{region}.amazonaws.com/{args.stage}"
    bodies = {"read": {"profileId": SYNTHETIC_PROFILE},
              "write": {"profileId": SYNTHETIC_PROFILE, "conversationId": "acxdmem-security-probe"}}
    outputs = endpoint_secret_arns(s.client("cloudformation"), f"{prefix}-api")
    secret_value = {r: sm.get_secret_value(SecretId=arn)["SecretString"]
                    for r, arn in outputs.items()}
    for route, other in (("read", "write"), ("write", "read")):
        url = f"{base}/memory/{route}"
        code = _post(url, {}, bodies[route])
        check(code == 401, f"/memory/{route} without secret header -> {code} (want 401)")
        code = _post(url, {"x-acxdmem-secret": "wrong-" + "x" * 40}, bodies[route])
        check(code == 403, f"/memory/{route} with a wrong secret -> {code} (want 403)")
        code = _post(url, {"x-acxdmem-secret": secret_value[other]}, bodies[route])
        check(code == 403, f"/memory/{route} with the {other} route's secret -> {code} (want 403)")

    print(f"{len(failures)} failure(s)" if failures else "all checks passed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
